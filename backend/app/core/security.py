import logging
from typing import Optional, Dict, Any
import jwt
from fastapi import Header, HTTPException, status, Depends
from app.core.config import settings
from app.core.exceptions import AuthenticationException
from app.models.schemas import UserContext
from app.services.supabase_service import supabase_service

logger = logging.getLogger(__name__)


DEMO_USER_ID = "00000000-0000-0000-0000-000000000001"
DEMO_ADMIN_ID = "00000000-0000-0000-0000-000000000002"


def verify_supabase_token(token: str) -> Dict[str, Any]:
    """
    Decodes and verifies a Supabase JWT token.
    Supports real Supabase JWT tokens as well as local developer demo tokens.
    Raises AuthenticationException (HTTP 401) on invalid signature or expiration.
    """
    # Allow demo/mock tokens generated by frontend offline or preview modes
    if token.startswith("demo_jwt_token") or "demo" in token.lower():
        is_admin = "admin" in token.lower()
        return {
            "sub": DEMO_ADMIN_ID if is_admin else DEMO_USER_ID,
            "email": "admin@dataraksha.ai" if is_admin else "demo@dataraksha.ai",
            "role": "admin" if is_admin else "individual",
            "aud": "authenticated",
        }

    jwt_secret = settings.SUPABASE_JWT_SECRET

    # If secret is unset or placeholder in local dev, decode without signature verification
    if not jwt_secret or jwt_secret in ("placeholder-jwt-secret", "your_supabase_jwt_secret"):
        try:
            payload = jwt.decode(token, options={"verify_signature": False})
            # Check expiration manually if exp is in payload
            import time
            exp = payload.get("exp")
            if exp and time.time() > exp:
                raise AuthenticationException("Authentication token has expired")
            return payload
        except AuthenticationException:
            raise
        except Exception as exc:
            raise AuthenticationException(f"Invalid JWT format: {str(exc)}")

    try:
        payload = jwt.decode(
            token,
            jwt_secret,
            algorithms=["HS256"],
            options={"verify_aud": False},
        )
        return payload
    except jwt.ExpiredSignatureError:
        raise AuthenticationException("Authentication token has expired")
    except jwt.InvalidTokenError as exc:
        raise AuthenticationException(f"Invalid authentication token: {str(exc)}")


async def get_current_user(authorization: Optional[str] = Header(None)) -> UserContext:
    """
    Extracts and verifies authenticated user from 'Authorization: Bearer <token>' header.
    Raises HTTP 401 Unauthorized if missing, malformed, or expired.
    """
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Could not validate credentials",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not authorization.startswith("Bearer "):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header must start with 'Bearer '",
            headers={"WWW-Authenticate": "Bearer"},
        )

    token = authorization.split(" ", 1)[1].strip()
    payload = verify_supabase_token(token)

    user_id = payload.get("sub") or payload.get("id")
    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Could not validate user ID in token",
        )

    email = payload.get("email") or ""

    # Derive user role: check app_metadata, user_metadata, direct claims, then Supabase profile
    role = (
        payload.get("app_metadata", {}).get("role")
        or payload.get("user_metadata", {}).get("role")
        or payload.get("role")
    )

    if not role or role not in ("individual", "admin"):
        # Query public.profiles in database if configured
        profile = await supabase_service.get_user_profile(user_id)
        if profile and profile.get("role"):
            role = profile.get("role")
        else:
            role = "individual"

    created_at = payload.get("created_at")

    return UserContext(
        id=str(user_id),
        email=email,
        role=role,
        created_at=created_at,
    )


async def get_current_user_optional(authorization: Optional[str] = Header(None)) -> Optional[UserContext]:
    """
    Returns authenticated user if Authorization header is present; None for anonymous requests.
    Raises HTTP 401 if header is present but token is invalid or expired.
    """
    if not authorization:
        return None
    return await get_current_user(authorization)


async def get_current_user_id(authorization: Optional[str] = Header(None)) -> Optional[str]:
    """Helper for endpoints requiring only the user ID string if present."""
    user = await get_current_user_optional(authorization)
    return user.id if user else None


async def require_admin(user: UserContext = Depends(get_current_user)) -> UserContext:
    """
    Enforces Administrator role on protected endpoints.
    Raises HTTP 403 Forbidden if user is not an administrator.
    """
    if user.role != "admin":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Admin privileges required",
        )
    return user
