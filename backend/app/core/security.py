import logging
import time
from typing import Optional, Dict, Any
import httpx
import jwt
from fastapi import Header, HTTPException, status, Depends
from app.core.config import settings
from app.core.exceptions import AuthenticationException
from app.models.schemas import UserContext
from app.services.supabase_service import supabase_service

logger = logging.getLogger(__name__)


DEMO_USER_ID = "00000000-0000-0000-0000-000000000001"
DEMO_ADMIN_ID = "00000000-0000-0000-0000-000000000002"

_jwks_client: Optional[jwt.PyJWKClient] = None


def get_jwks_client() -> Optional[jwt.PyJWKClient]:
    """Returns cached PyJWKClient configured with Supabase JWKS endpoint."""
    global _jwks_client
    if _jwks_client is None and settings.SUPABASE_URL:
        jwks_url = f"{settings.SUPABASE_URL.rstrip('/')}/auth/v1/.well-known/jwks.json"
        headers = {}
        if settings.SUPABASE_KEY:
            headers["apikey"] = settings.SUPABASE_KEY
        try:
            _jwks_client = jwt.PyJWKClient(jwks_url, headers=headers)
        except Exception as e:
            logger.warning(f"Could not initialize Supabase PyJWKClient: {e}")
    return _jwks_client


def verify_with_supabase_rest(token: str) -> Dict[str, Any]:
    """Verifies token directly against Supabase /auth/v1/user endpoint as authoritative fallback."""
    if not settings.SUPABASE_URL or not settings.SUPABASE_KEY:
        raise AuthenticationException("Supabase credentials not configured")

    user_url = f"{settings.SUPABASE_URL.rstrip('/')}/auth/v1/user"
    try:
        with httpx.Client(timeout=6.0) as client:
            resp = client.get(
                user_url,
                headers={
                    "apikey": settings.SUPABASE_KEY,
                    "Authorization": f"Bearer {token}",
                },
            )
            if resp.status_code == 200:
                user_data = resp.json()
                return {
                    "sub": user_data.get("id"),
                    "id": user_data.get("id"),
                    "email": user_data.get("email"),
                    "role": user_data.get("role", "authenticated"),
                    "app_metadata": user_data.get("app_metadata", {}),
                    "user_metadata": user_data.get("user_metadata", {}),
                    "aud": user_data.get("aud", "authenticated"),
                }
            elif resp.status_code in (401, 403):
                raise AuthenticationException("Authentication token is invalid or expired")
            else:
                raise AuthenticationException(f"Supabase auth check returned HTTP {resp.status_code}")
    except AuthenticationException:
        raise
    except Exception as exc:
        logger.error(f"Error querying Supabase user endpoint: {exc}")
        raise AuthenticationException("Could not verify authentication credentials")


def verify_supabase_token(token: str) -> Dict[str, Any]:
    """
    Decodes and verifies a Supabase JWT token.
    Supports asymmetric ES256/RS256 tokens (from Supabase Auth), symmetric HS256 tokens,
    and developer demo tokens.
    Raises AuthenticationException (HTTP 401) on invalid signature or expiration.
    """
    # 1. Allow demo/mock tokens generated by frontend offline or preview modes
    if token.startswith("demo_jwt_token") or "demo" in token.lower():
        is_admin = "admin" in token.lower()
        parts = token.split("_")
        custom_email = None
        if len(parts) >= 3 and ("@" in parts[2] or "---" in parts[2]):
            custom_email = parts[2].replace("---", "@")
        elif len(parts) >= 4 and ("@" in parts[3] or "---" in parts[3]):
            custom_email = parts[3].replace("---", "@")

        email = custom_email or ("admin@dataraksha.ai" if is_admin else "demo@dataraksha.ai")
        reg_users = getattr(supabase_service, "_registered_users", {})
        existing = next((u for u in reg_users.values() if u.get("email", "").lower() == email.lower()), None)
        sub_id = existing["id"] if existing else (DEMO_ADMIN_ID if is_admin else DEMO_USER_ID)
        return {
            "sub": sub_id,
            "id": sub_id,
            "email": email,
            "role": "admin" if is_admin else "individual",
            "aud": "authenticated",
        }

    # 2. Inspect token header to identify signing algorithm
    try:
        header = jwt.get_unverified_header(token)
        alg = header.get("alg", "HS256")
    except Exception as exc:
        raise AuthenticationException(f"Invalid JWT format: {str(exc)}")

    # 3. Handle asymmetric algorithms (ES256, RS256) via Supabase JWKS
    if alg in ("ES256", "RS256"):
        jwks = get_jwks_client()
        if jwks:
            try:
                signing_key = jwks.get_signing_key_from_jwt(token)
                payload = jwt.decode(
                    token,
                    signing_key.key,
                    algorithms=["ES256", "RS256"],
                    options={"verify_aud": False},
                )
                return payload
            except jwt.ExpiredSignatureError:
                raise AuthenticationException("Authentication token has expired")
            except Exception as exc:
                logger.warning(f"JWKS verification failed ({exc}); falling back to Supabase REST verification")

        # Fallback to Supabase REST /auth/v1/user
        return verify_with_supabase_rest(token)

    # 4. Handle symmetric algorithm (HS256) via SUPABASE_JWT_SECRET
    jwt_secret = settings.SUPABASE_JWT_SECRET
    if not jwt_secret or jwt_secret in ("placeholder-jwt-secret", "your_supabase_jwt_secret"):
        try:
            payload = jwt.decode(token, options={"verify_signature": False})
            exp = payload.get("exp")
            if exp and time.time() > exp:
                raise AuthenticationException("Authentication token has expired")
            return payload
        except AuthenticationException:
            raise
        except Exception as exc:
            raise AuthenticationException(f"Invalid JWT format: {str(exc)}")

    try:
        payload = jwt.decode(
            token,
            jwt_secret,
            algorithms=["HS256"],
            options={"verify_aud": False},
        )
        return payload
    except jwt.ExpiredSignatureError:
        raise AuthenticationException("Authentication token has expired")
    except jwt.InvalidTokenError:
        # Fallback to Supabase REST if secret didn't match (e.g. project rotation)
        try:
            return verify_with_supabase_rest(token)
        except Exception:
            raise AuthenticationException("Invalid authentication token")


async def get_current_user(authorization: Optional[str] = Header(None)) -> UserContext:
    """
    Extracts and verifies authenticated user from 'Authorization: Bearer <token>' header.
    Raises HTTP 401 Unauthorized if missing, malformed, or expired.
    """
    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Could not validate credentials",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not authorization.startswith("Bearer "):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authorization header must start with 'Bearer '",
            headers={"WWW-Authenticate": "Bearer"},
        )

    token = authorization.split(" ", 1)[1].strip()
    payload = verify_supabase_token(token)

    user_id = payload.get("sub") or payload.get("id")
    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Could not validate user ID in token",
        )

    email = payload.get("email") or ""
    clean_email = email.strip().lower()

    # Strictly secure role resolution:
    # 1. Check server-side allowlist of Supabase user UUIDs from environment variables
    admin_uuids = [
        u.strip() for u in (getattr(settings, "ADMIN_USER_IDS", "") or "").split(",") if u.strip()
    ]
    is_allowlisted_uuid = str(user_id) in admin_uuids

    # 2. Check server-side allowlist of administrator emails from environment variables
    admin_emails = [
        e.strip().lower()
        for e in (
            (getattr(settings, "ADMIN_EMAILS", "") or "")
            + ","
            + (getattr(settings, "INITIAL_ADMIN_EMAILS", "mk9205507@gmail.com") or "")
        ).split(",")
        if e.strip()
    ]
    is_allowlisted_email = clean_email in admin_emails

    # 3. Check server-only app_metadata claim (set only via service-role admin API; ignore user_metadata)
    app_meta_role = payload.get("app_metadata", {}).get("role")
    direct_role = payload.get("role") if payload.get("role") in ("admin", "individual") else None

    if is_allowlisted_uuid or is_allowlisted_email or app_meta_role == "admin" or direct_role == "admin":
        role = "admin"
    else:
        # 4. Authoritative database lookup in public.profiles
        profile = await supabase_service.get_user_profile(str(user_id))
        if profile and profile.get("role") == "admin":
            role = "admin"
        else:
            role = "individual"

    created_at = payload.get("created_at")

    # Dynamically track real user activity in registry
    if email and str(user_id) not in ("00000000-0000-0000-0000-000000000001", "00000000-0000-0000-0000-000000000002"):
        try:
            await supabase_service.record_user_activity(
                user_id=str(user_id),
                email=clean_email,
                role=role,
            )
        except Exception as exc:
            logger.debug(f"Record user activity note: {exc}")

    return UserContext(
        id=str(user_id),
        email=email,
        role=role,
        created_at=created_at,
    )



async def get_current_user_optional(authorization: Optional[str] = Header(None)) -> Optional[UserContext]:
    """
    Returns authenticated user if Authorization header is present and valid; None for anonymous requests.
    Gracefully returns None if token is invalid or expired so public endpoints do not fail.
    """
    if not authorization:
        return None
    try:
        return await get_current_user(authorization)
    except HTTPException:
        logger.info("Optional authorization token invalid or expired. Treating as anonymous guest.")
        return None


async def get_current_user_id(authorization: Optional[str] = Header(None)) -> Optional[str]:
    """Helper for endpoints requiring only the user ID string if present."""
    user = await get_current_user_optional(authorization)
    return user.id if user else None


async def require_admin(user: UserContext = Depends(get_current_user)) -> UserContext:
    """
    Enforces Administrator role on protected endpoints.
    Raises HTTP 403 Forbidden if user is not an administrator.
    """
    if user.role != "admin":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Admin privileges required",
        )
    return user
